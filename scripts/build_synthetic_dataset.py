def build_document() -> dict:
    rows = []
    group_index = 0

    def add_group(category: str, pairs: list[tuple[str, str, int, int]]) -> None:
        nonlocal group_index
        group_index += 1
        group = f"group-{group_index:02}"
        for text_a, text_b, event_a, event_b in pairs:
            rows.append(
                {
                    "pair_id": f"synthetic-{len(rows) + 1:03}",
                    "text_a": text_a,
                    "text_b": text_b,
                    "label": int(event_a == event_b),
                    "category": category,
                    "event_group_id": group,
                    "event_id_a": f"{group}-claim-{event_a}",
                    "event_id_b": f"{group}-claim-{event_b}",
                    "explanation": EXPLANATIONS[category],
                }
            )

    for category, texts in TRIPLETS:
        positive = category in {"same_event_paraphrase", "near_identical"}
        add_group(
            category,
            [
                (texts[a], texts[b], 0 if positive else a, 0 if positive else b)
                for a, b in combinations(range(3), 2)
            ],
        )
    for positive, negatives in NEGATIONS:
        add_group(
            "negation_difference",
            [(positive, negative, 0, 1) for negative in negatives],
        )
    for headline, expansions in SHORT_LONG:
        add_group(
            "short_long", [(headline, expansion, 0, 0) for expansion in expansions]
        )
    return {
        "schema_version": 1,
        "name": "synthetic-persian-news-v1",
        ("description"): (
            "تمام متن\u200cها و رویدادها ساختگی\u200cاند؛ هیچ نمونه\u200cای از تلگرام،"
            " بله یا گزارش واقعی گردآوری نشده است."
        ),
        "language": "fa",
        "synthetic": True,
        "pairs": assign_group_splits(rows),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check the committed fixture without rewriting it",
    )
    args = parser.parse_args()
    document = build_document()
    dataset = validate_dataset(document)
    serialized = json.dumps(document, ensure_ascii=False, indent=2) + "\n"
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != serialized:
            parser.exit(
                1, "Synthetic dataset differs from the deterministic builder.\n"
            )
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(serialized, encoding="utf-8", newline="\n")
    print(json.dumps(dataset.summary(), indent=2))
    return 0


